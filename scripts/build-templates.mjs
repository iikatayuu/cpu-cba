// Generates theme/templates/*.json (and config/settings_data.json) from content/*.json.
// Run: node scripts/build-templates.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'));
const college = read('content/college.json');
const trivia = read('content/trivia.json');
const T = join(root, 'theme/templates');
mkdirSync(T, { recursive: true });

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const paras = (arr) => arr.map((p) => `<p>${esc(p)}</p>`).join('');
const blocks = (prefix, items, type, map) => {
  const b = {}; const order = [];
  items.forEach((it, i) => { const id = `${prefix}_${i + 1}`; b[id] = { type, settings: map(it) }; order.push(id); });
  return { blocks: b, block_order: order };
};
const tpl = (sections, order) => ({ sections, order: order || Object.keys(sections) });
const write = (name, obj) => {
  const header = '/*\n * Generated by scripts/build-templates.mjs from content/*.json.\n * Edits made in the theme editor are kept by Shopify; re-running the script overwrites them.\n */\n';
  writeFileSync(join(T, name), header + JSON.stringify(obj, null, 2) + '\n');
};

